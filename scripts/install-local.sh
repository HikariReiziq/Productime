#!/usr/bin/env bash
# Install Productime for the current user under ~/.local, with a GNOME launcher and icon.
# Nothing here needs root, and nothing is written outside your home directory.
#
#   scripts/install-local.sh              install or update
#   scripts/install-local.sh --uninstall  remove the app (your saved data is kept)
set -euo pipefail

APP_ID="org.productime.Productime"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ICON_SIZES=(64 128 256 512)

log() { printf '%s\n' "$*"; }
die() { printf 'install-local: %s\n' "$*" >&2; exit 1; }

usage() {
    sed -n '2,6p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

[ "$(id -u)" -ne 0 ] || die "run this as your normal user, not as root: it installs into your home directory"
[ -n "${HOME:-}" ] && [ -d "$HOME" ] || die "HOME is not set to an existing directory"

# The XDG spec says a relative XDG_DATA_HOME must be ignored.
case "${XDG_DATA_HOME:-}" in
    /*) DATA_HOME="$XDG_DATA_HOME" ;;
    *) DATA_HOME="$HOME/.local/share" ;;
esac
BIN_DIR="$HOME/.local/bin"
APP_DIR="$DATA_HOME/productime-app"
LAUNCHER="$BIN_DIR/productime"
DESKTOP_DIR="$DATA_HOME/applications"
DESKTOP_FILE="$DESKTOP_DIR/$APP_ID.desktop"
ICON_ROOT="$DATA_HOME/icons/hicolor"
USER_DATA="$DATA_HOME/productime"

# Single-quote a value for /bin/sh.
shell_quote() {
    printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"
}

# Quote a path for the Exec key of a desktop entry.
desktop_exec_quote() {
    case "$1" in
        *[!A-Za-z0-9_./+-]*)
            printf '"%s"' "$(printf '%s' "$1" | sed -e 's/[\\"`$]/\\&/g')"
            ;;
        *) printf '%s' "$1" ;;
    esac
}

refresh_caches() {
    if command -v update-desktop-database >/dev/null 2>&1; then
        update-desktop-database -q "$DESKTOP_DIR" 2>/dev/null || true
    fi
    local tool
    for tool in gtk4-update-icon-cache gtk-update-icon-cache; do
        if command -v "$tool" >/dev/null 2>&1 && [ -d "$ICON_ROOT" ]; then
            "$tool" -q -t -f --ignore-theme-index "$ICON_ROOT" 2>/dev/null || true
            break
        fi
    done
}

check_runtime() {
    command -v python3 >/dev/null 2>&1 || die "python3 is not installed"
    if ! python3 - <<'PY'
import sys

if sys.version_info < (3, 14):
    sys.exit("Python 3.14 or newer is required, found " + sys.version.split()[0])
import gi

for namespace, version in (("Gtk", "4.0"), ("Adw", "1"), ("Gst", "1.0")):
    gi.require_version(namespace, version)
import cairo  # noqa: F401
PY
    then
        die "missing system libraries. Install them with:
    sudo dnf install python3-gobject gtk4 libadwaita gstreamer1-plugins-good python3-cairo libnotify"
    fi
}

remove_app_dir() {
    # Guard the one recursive delete: only ever the app directory this script created.
    case "$APP_DIR" in
        */productime-app) rm -rf -- "$APP_DIR" ;;
        *) die "refusing to remove unexpected path: $APP_DIR" ;;
    esac
}

install_app() {
    check_runtime
    [ -d "$ROOT/src/productime" ] || die "src/productime not found next to this script"
    [ -d "$ROOT/Assets" ] || die "Assets/ not found next to this script"

    local staging="$APP_DIR.new.$$"
    rm -rf -- "$staging"
    mkdir -p "$staging"
    trap 'rm -rf -- "$staging"' EXIT
    cp -R "$ROOT/src/productime" "$staging/productime"
    find "$staging" -type d -name '__pycache__' -prune -exec rm -rf -- {} +
    mkdir "$staging/Assets"
    cp "$ROOT"/Assets/*.mp3 "$ROOT/Assets/Productime Icon.png" "$staging/Assets/"
    # Swap the finished copy in, so a failed copy never leaves a half-installed app.
    remove_app_dir
    mkdir -p "$(dirname "$APP_DIR")"
    mv "$staging" "$APP_DIR"
    trap - EXIT

    mkdir -p "$BIN_DIR"
    # -P keeps the working directory off sys.path and -s skips the per-user site
    # directory, so only the system libraries and this copy of the app are imported.
    cat >"$LAUNCHER" <<EOF
#!/bin/sh
# Productime launcher, generated by scripts/install-local.sh.
PYTHONPATH=$(shell_quote "$APP_DIR") exec /usr/bin/python3 -P -s -m productime "\$@"
EOF
    chmod 755 "$LAUNCHER"

    local size
    for size in "${ICON_SIZES[@]}"; do
        install -D -m 644 "$ROOT/packaging/icons/hicolor/${size}x${size}/apps/$APP_ID.png" \
            "$ICON_ROOT/${size}x${size}/apps/$APP_ID.png"
    done

    mkdir -p "$DESKTOP_DIR"
    local exec_value line
    exec_value="$(desktop_exec_quote "$LAUNCHER")"
    : >"$DESKTOP_FILE"
    while IFS= read -r line || [ -n "$line" ]; do
        printf '%s\n' "${line//@EXEC@/"$exec_value"}" >>"$DESKTOP_FILE"
    done <"$ROOT/packaging/$APP_ID.desktop.in"
    chmod 644 "$DESKTOP_FILE"
    if command -v desktop-file-validate >/dev/null 2>&1; then
        desktop-file-validate "$DESKTOP_FILE" || die "the generated desktop file is invalid: $DESKTOP_FILE"
    fi
    refresh_caches

    log "Productime is installed."
    log "  App:       $APP_DIR"
    log "  Launcher:  $LAUNCHER"
    log "  Desktop:   $DESKTOP_FILE"
    log "  Your data: $USER_DATA (created on first run)"
    log "Open it from the GNOME app grid, or run: $LAUNCHER"
}

uninstall_app() {
    remove_app_dir
    rm -f -- "$LAUNCHER" "$DESKTOP_FILE"
    local size
    for size in "${ICON_SIZES[@]}"; do
        rm -f -- "$ICON_ROOT/${size}x${size}/apps/$APP_ID.png"
    done
    refresh_caches
    log "Productime was removed."
    log "Your saved targets, alarms, timers, and reports were kept in: $USER_DATA"
}

case "${1:-}" in
    "") install_app ;;
    --uninstall) uninstall_app ;;
    -h | --help) usage ;;
    *) usage >&2; exit 2 ;;
esac
